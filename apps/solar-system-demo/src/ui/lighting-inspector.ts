export interface LightingInspectorHandle {
  readonly tuning: () => LightingInspectorTuning;
  dispose(): void;
}

export function installLightingInspector(
  onChange: (tuning: LightingInspectorTuning) => void,
): LightingInspectorHandle {
  ensureInspectorStyles();
  document.getElementById("lighting-inspector")?.remove();
  document.querySelector<HTMLButtonElement>('#control-nav button[data-target="lighting-inspector"]')?.remove();

  let current = loadStoredTuning();
  const section = document.createElement("section");
  section.className = "panel-section";
  section.id = "lighting-inspector";
  section.tabIndex = -1;
  section.setAttribute("aria-labelledby", "lighting-inspector-heading");
  section.innerHTML = `
    <div class="section-heading">
      <div>
        <p class="section-kicker">Debug presentation</p>
        <h2 id="lighting-inspector-heading">Lighting inspector</h2>
      </div>
      <span class="scenario-badge">Live</span>
    </div>
    <p class="lighting-inspector-intro">Temporary runtime controls for the shared planetary lighting pipeline. Values are global, persist locally across reloads, and do not modify OrbitEngine physics or body datasets.</p>
  `;

  const inputs = new Map<keyof LightingInspectorTuning, HTMLInputElement>();
  const outputs = new Map<keyof LightingInspectorTuning, HTMLOutputElement>();

  const emit = (): void => {
    try {
      globalThis.localStorage?.setItem(STORAGE_KEY, JSON.stringify(current));
    } catch {
      // Storage is convenience only; rendering must not depend on it.
    }
    onChange(Object.freeze({ ...current }));
  };

  for (const group of CONTROL_GROUPS) {
    const groupElement = document.createElement("div");
    groupElement.className = "lighting-inspector-group";
    const heading = document.createElement("h3");
    heading.textContent = group.title;
    const description = document.createElement("p");
    description.textContent = group.description;
    groupElement.append(heading, description);

    for (const control of group.controls) {
      const row = document.createElement("div");
      row.className = "lighting-inspector-control";
      const label = document.createElement("label");
      const id = `lighting-inspector-${control.key}`;
      label.htmlFor = id;
      label.textContent = control.label;
      const output = document.createElement("output");
      output.setAttribute("for", id);
      output.value = formatValue(current[control.key], control.step);
      const input = document.createElement("input");
      input.id = id;
      input.type = "range";
      input.min = String(control.min);
      input.max = String(control.max);
      input.step = String(control.step);
      input.value = String(current[control.key]);
      input.setAttribute("aria-describedby", `${id}-help`);
      const help = document.createElement("small");
      help.id = `${id}-help`;
      help.textContent = control.help;
      input.addEventListener("input", () => {
        const value = clamp(Number(input.value), control);
        current = Object.freeze({ ...current, [control.key]: value });
        output.value = formatValue(value, control.step);
        emit();
      });
      inputs.set(control.key, input);
      outputs.set(control.key, output);
      row.append(label, output, input, help);
      groupElement.append(row);
    }
    section.append(groupElement);
  }

  const actions = document.createElement("div");
  actions.className = "lighting-inspector-actions";
  const reset = document.createElement("button");
  reset.className = "secondary-button";
  reset.type = "button";
  reset.textContent = "Reset defaults";
  const copy = document.createElement("button");
  copy.className = "secondary-button";
  copy.type = "button";
  copy.textContent = "Copy values";
  const status = document.createElement("p");
  status.className = "lighting-inspector-copy-status";
  status.setAttribute("aria-live", "polite");

  reset.addEventListener("click", () => {
    current = { ...DEFAULT_LIGHTING_INSPECTOR_TUNING };
    for (const group of CONTROL_GROUPS) {
      for (const control of group.controls) {
        inputs.get(control.key)!.value = String(current[control.key]);
        outputs.get(control.key)!.value = formatValue(current[control.key], control.step);
      }
    }
    emit();
    status.textContent = "Defaults restored.";
  });

  copy.addEventListener("click", async () => {
    const text = JSON.stringify(current, null, 2);
    try {
      await navigator.clipboard.writeText(text);
      status.textContent = "Values copied to clipboard.";
    } catch {
      status.textContent = text;
    }
  });
  actions.append(reset, copy);
  section.append(actions, status);

  const viewSection = document.getElementById("view-section");
  if (viewSection !== null) viewSection.insertAdjacentElement("afterend", section);
  else document.getElementById("panel-content")?.append(section);

  const nav = document.getElementById("control-nav");
  if (nav !== null) {
    const button = document.createElement("button");
    button.type = "button";
    button.dataset.target = "lighting-inspector";
    button.setAttribute("aria-controls", "lighting-inspector");
    button.textContent = "Lighting";
    button.addEventListener("click", () => {
      nav.querySelectorAll("button[data-target]").forEach((candidate) => candidate.removeAttribute("aria-current"));
      button.setAttribute("aria-current", "true");
      section.scrollIntoView({ block: "start", behavior: "smooth" });
      section.focus({ preventScroll: true });
    });
    const viewButton = nav.querySelector<HTMLButtonElement>('button[data-target="view-section"]');
    if (viewButton?.nextSibling !== null && viewButton?.nextSibling !== undefined) nav.insertBefore(button, viewButton.nextSibling);
    else nav.append(button);
  }

  emit();

  return {
    tuning: () => Object.freeze({ ...current }),
    dispose() {
      section.remove();
      document.querySelector<HTMLButtonElement>('#control-nav button[data-target="lighting-inspector"]')?.remove();
    },
  };
}
