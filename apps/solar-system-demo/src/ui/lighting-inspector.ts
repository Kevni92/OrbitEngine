function clamp(value: number, control: InspectorControl): number {
  if (!Number.isFinite(value)) return DEFAULT_LIGHTING_INSPECTOR_TUNING[control.key];
  return Math.min(control.max, Math.max(control.min, value));
}

function loadStoredTuning(): LightingInspectorTuning {
  try {
    const raw = globalThis.localStorage?.getItem(STORAGE_KEY);
    if (raw === null || raw === undefined) return { ...DEFAULT_LIGHTING_INSPECTOR_TUNING };
    const parsed = JSON.parse(raw) as Partial<Record<keyof LightingInspectorTuning, unknown>>;
    const next = { ...DEFAULT_LIGHTING_INSPECTOR_TUNING } as Record<keyof LightingInspectorTuning, number>;
    for (const group of CONTROL_GROUPS) {
      for (const control of group.controls) {
        const candidate = parsed[control.key];
        if (typeof candidate === "number") next[control.key] = clamp(candidate, control);
      }
    }
    return next;
  } catch {
    return { ...DEFAULT_LIGHTING_INSPECTOR_TUNING };
  }
}

function formatValue(value: number, step: number): string {
  const decimals = step >= 1 ? 0 : step >= 0.1 ? 1 : 2;
  return value.toFixed(decimals);
}

